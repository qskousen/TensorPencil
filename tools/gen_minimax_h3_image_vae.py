#!/usr/bin/env python3
"""Pin MiniMax-H3-Image's VAE DECODE by executing ComfyUI's own `MiniMaxH3ImageVAE`.

The image decoder is the video VAE's ViT with one frame per token (`patch_t` 1),
a 2D rope over (h, w) covering half the head, a 2D `post_quant_conv`, and no
latent statistics in the file (the reference falls back to its own constants).
The real one is 16 heads wide; this builds the real class with the decoder's head
count shrunk to 2 and the encoder stubbed out (the encode side is pinned by
tools/gen_minimax_h3_vae_encode.py), then runs the real `decode` on a latent wide
enough to tile, so the still-frame path, the tiling and the finalize are all the
reference's own.

The fixture carries no `latents_mean` / `latents_std`, like the release file, so
the loader's fallback is under test too.

Emits src/models/assets/minimax_h3_image_vae.safetensors.

Usage:
    /home/qt/genai/comfyui/nvenv/bin/python tools/gen_minimax_h3_image_vae.py
"""

import json
import os
import sys

OUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "src", "models", "assets", "minimax_h3_image_vae.safetensors",
)

COMFY = "/home/qt/genai/comfyui"
sys.path.insert(0, COMFY)
os.chdir(COMFY)

import torch  # noqa: E402
import safetensors.torch  # noqa: E402

import comfy.ldm.minimax.vae as mvae  # noqa: E402
from comfy.ldm.modules.attention import attention_pytorch  # noqa: E402

mvae.optimized_attention = attention_pytorch

HEADS = 2
LAYERS = 2
Z_CH = 24
# 18 latent columns are 288 px: two 256 px tiles with a 224 px overlap region
LAT_H, LAT_W = 3, 18


class _Stub(torch.nn.Module):
    def __init__(self, *a, **kw):
        super().__init__()


def main():
    torch.manual_seed(20261110)
    real_enc, real_dec = mvae.EncoderFCN3D, mvae.ViT3DDecoder
    mvae.EncoderFCN3D = _Stub
    mvae.ViT3DDecoder = lambda **kw: real_dec(**dict(kw, heads=HEADS))
    try:
        vae = mvae.MiniMaxH3ImageVAE(num_layers=LAYERS)
    finally:
        mvae.EncoderFCN3D, mvae.ViT3DDecoder = real_enc, real_dec
    vae.eval()
    assert vae.decoder.patch_size_t == 1 and vae.decoder.pos_embed.n_dim == 2
    assert vae.still_frame == 0

    sd = {}
    for name, p in vae.state_dict().items():
        if not (name.startswith("decoder.") or name.startswith("post_quant_conv.")):
            continue
        short = name[len("decoder."):]
        if short.endswith("norm1.weight") or short.endswith("norm2.weight") or short == "norm_out.weight":
            t = 1.0 + torch.randn(p.shape) * 0.1
        elif short.startswith("transformer_blocks.") and ".scale" in short:
            t = 0.5 + torch.randn(p.shape) * 0.1
        elif name.endswith(".bias"):
            t = torch.randn(p.shape) * 0.1
        elif p.dim() == 2:
            t = torch.randn(p.shape) / (p.shape[1] ** 0.5)
        elif name == "post_quant_conv.weight":
            t = torch.randn(p.shape) / (Z_CH ** 0.5)
        else:
            t = torch.randn(p.shape) * 0.1
        sd[name] = t.float()
    missing, unexpected = vae.load_state_dict(sd, strict=False)
    assert not unexpected and all(not (k.startswith("decoder.") or k.startswith("post_quant_conv.")) for k in missing), missing
    for prm in vae.parameters():
        prm.requires_grad_(False)

    z = torch.randn(1, Z_CH, 1, LAT_H, LAT_W)
    with torch.inference_mode():
        out = vae.decode(z)
    assert out.shape == (1, 3, 1, LAT_H * 16, LAT_W * 16), out.shape
    interior = float(((out > 1e-4) & (out < 1 - 1e-4)).float().mean())
    assert interior > 0.5, "output is mostly clamped (%.3f)" % interior

    # Teeth: the tiling must matter, and so must the 2D rope's axis choice.
    def rel(a, b):
        return float((a - b).norm() / b.norm())

    vae.tiling = False
    with torch.inference_mode():
        whole = vae.decode(z)
    vae.tiling = True
    d_tile = rel(whole, out)
    assert d_tile > 1e-3, "the 288 px case does not tile (%.2e)" % d_tile

    real_ids = mvae.create_token_ids
    mvae.create_token_ids = lambda dims, device, dtype: real_ids(dims[::-1], device, dtype)
    try:
        with torch.inference_mode():
            swapped = vae.decode(z)
    finally:
        mvae.create_token_ids = real_ids
    d_axes = rel(swapped, out)
    assert d_axes > 1e-3, "the rope's (h, w) order is invisible (%.2e)" % d_axes
    print("  interior %.3f  sensitivity: tiling %.4f  rope axes %.4f" % (interior, d_tile, d_axes))

    tensors = dict(sd)
    tensors["in.z"] = z
    tensors["out.rgb"] = out
    meta = {
        "shape": json.dumps({"latent_h": LAT_H, "latent_w": LAT_W, "heads": HEADS, "layers": LAYERS}),
        "note": "generated by tools/gen_minimax_h3_image_vae.py from "
                "comfy.ldm.minimax.vae.MiniMaxH3ImageVAE.decode; do not hand-edit",
    }
    tensors = {k: v.contiguous() for k, v in tensors.items()}
    safetensors.torch.save_file(tensors, OUT, metadata=meta)
    print("wrote %s: %d tensors, %.2f MB" % (OUT, len(tensors), os.path.getsize(OUT) / 1048576))


if __name__ == "__main__":
    sys.exit(main())
