"""Generate src/core/nfc_tables.zig and its fixture src/core/assets/nfc_fixtures.json.

NFC is what transformers' slow `Qwen2Tokenizer` applies to a prompt before anything
else (`prepare_for_tokenization`), and ComfyUI tokenizes every Qwen text encoder
through it. The tables are Python's own `unicodedata`, the same module that call
uses, so the Unicode version is the reference's:

  - canonical decompositions, one level (the runtime recurses), singletons included;
  - canonical combining classes, the non-zero ones;
  - primary composites: a two-character canonical decomposition that NFC actually
    recomposes. Asking `normalize` rather than reading the decomposition alone is
    what keeps the composition exclusions out without copying their list.

Hangul syllables are algorithmic in the standard and in the runtime, so they appear
in neither table.

The fixture holds, for every code point with a canonical decomposition, its NFD and
NFC, plus a handful of strings that exercise reordering and blocking.

Run with ComfyUI's venv python, the reference's interpreter:
  ~/genai/comfyui/nvenv/bin/python tools/gen_nfc_tables.py
"""
import json
import os
import unicodedata as ud

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "src", "core", "nfc_tables.zig")
FIXTURE = os.path.join(REPO, "src", "core", "assets", "nfc_fixtures.json")

S_BASE, S_COUNT = 0xAC00, 11172


def canonical(cp):
    d = ud.decomposition(chr(cp))
    if not d or d.startswith("<"):
        return None
    return [int(x, 16) for x in d.split()]


decomp, ccc, comp = [], [], []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF or S_BASE <= cp < S_BASE + S_COUNT:
        continue
    c = ud.combining(chr(cp))
    if c:
        ccc.append((cp, c))
    d = canonical(cp)
    if d is None:
        continue
    decomp.append((cp, d))
    if len(d) == 2 and ud.normalize("NFC", chr(d[0]) + chr(d[1])) == chr(cp):
        comp.append((d[0], d[1], cp))
comp.sort()

pool, offs = [], []
for _, d in decomp:
    offs.append(len(pool))
    pool.extend(d)
offs.append(len(pool))

lines = [
    "//! Unicode NFC tables, generated by tools/gen_nfc_tables.py from python's",
    f"//! `unicodedata` (Unicode {ud.unidata_version}); do not edit by hand.",
    "",
    f'pub const unicode_version = "{ud.unidata_version}";',
    "",
    "pub const Ccc = struct { cp: u21, class: u8 };",
    "pub const Pair = struct { a: u21, b: u21, c: u21 };",
    "",
    "/// Non-zero canonical combining classes, by code point.",
    "pub const ccc = [_]Ccc{",
]
lines += [f"    .{{ .cp = 0x{cp:x}, .class = {c} }}," for cp, c in ccc]
lines += ["};", "", "/// Code points with a canonical decomposition, sorted; their mapping is",
          "/// `decomp_pool[decomp_off[i]..decomp_off[i + 1]]`, one level deep.",
          "pub const decomp_cp = [_]u21{"]
lines += [f"    0x{cp:x}," for cp, _ in decomp]
lines += ["};", "", "pub const decomp_off = [_]u16{"]
lines += [f"    {o}," for o in offs]
lines += ["};", "", "pub const decomp_pool = [_]u21{"]
lines += [f"    0x{x:x}," for x in pool]
lines += ["};", "", "/// Primary composites, sorted by (a, b).", "pub const comp = [_]Pair{"]
lines += [f"    .{{ .a = 0x{a:x}, .b = 0x{b:x}, .c = 0x{c:x} }}," for a, b, c in comp]
lines += ["};", ""]
with open(OUT, "w") as f:
    f.write("\n".join(lines))

cases = []
for cp, _ in decomp:
    s = ud.normalize("NFD", chr(cp))
    cases.append([s, ud.normalize("NFC", s)])
extra = [
    "cafe\u0301 nai\u0308ve",           # decomposed latin
    "a\u0323\u0302 a\u0302\u0323",      # two marks, both orders: reordering
    "\u1100\u1161\u11a8 \u1100\u1161",  # Hangul LVT and LV from jamo
    "\uac00\u11a8",                     # LV syllable plus a trailing T
    "\u212b \u2126 \u0915\u093c",       # singletons and an exclusion
    "e\u0301\u0301 o\u0308\u0304",      # a blocked second mark, a chained composite
    "\u0301e",                          # a leading combining mark
    "ascii only, nothing to do",
    "\U0001d15e \u0f71\u0f72",          # excluded and non-starter decompositions
]
for s in extra:
    cases.append([s, ud.normalize("NFC", s)])
with open(FIXTURE, "w") as f:
    json.dump({"unicode_version": ud.unidata_version, "cases": cases}, f, ensure_ascii=False)

print(f"{len(ccc)} combining classes, {len(decomp)} decompositions ({len(pool)} pool), "
      f"{len(comp)} composites, {len(cases)} fixture cases")
